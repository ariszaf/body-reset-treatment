export type LegalDoc = keyof typeof docs;

/** Render a doc: keep ONE cookie mode, resolve placeholders, drop empty optional lines, strip operator comments. */
export function renderLegal(doc: LegalDoc): string {
  const keep = legalConfig.cookieMode;
  const drop = keep === 'A' ? 'B' : 'A';
  let t = docs[doc];

  // 1) Mode filter — exactly one mode survives (markers in 3 synchronized spots).
  // Anchor the end on the END *comment* ("<!-- MODE:X:END") — the START comment's
  // own text mentions "MODE:X:END", which a naive non-greedy match would stop at.
  t = t.replace(new RegExp(`<!-- MODE:${drop}:START[\\s\\S]*?<!-- MODE:${drop}:END[^>]*?-->`, 'g'), '');
  t = t.replace(new RegExp(`<!-- MODE:${keep}:START[\\s\\S]*?-->`, 'g'), '');
  t = t.replace(new RegExp(`<!-- MODE:${keep}:END[^>]*?-->`, 'g'), '');

  // 2) Placeholder resolution (site.ts + legalConfig)
  const EMPTY = '\u2205'; // sentinel for empty optionals → their whole line is dropped
  const map: Record<string, string> = {
    BUSINESS_NAME: site.name,
    SITE_URL: site.url,
    CONTACT_EMAIL: site.email,
    LAST_UPDATED: legalConfig.lastUpdated,
    VERSION: legalConfig.version,
    RETENTION_CONTACT: legalConfig.retentionContact,
    JURISDICTION_CITY: legalConfig.jurisdictionCity,
    GOVERNING_LAW: legalConfig.governingLaw,
    EMAIL_PROVIDER: legalConfig.emailProvider,
    ANALYTICS_TOOL: legalConfig.analyticsTool,
    TRANSFER_MECHANISM_NOTES: legalConfig.transferMechanismNotes,
    CONTROLLER_LEGAL_NAME: legalConfig.controllerLegalName || EMPTY,
    CONTROLLER_DETAILS: legalConfig.controllerDetails || EMPTY,
    CONTROLLER_PHONE: legalConfig.controllerPhone || site.phone || EMPTY,
    DPO_DETAILS: legalConfig.dpoDetails || EMPTY,
  };
  t = t.replace(/\[([A-Z_]{3,})\]/g, (m, key) => (key in map ? map[key] : m));

  // 3) Drop lines/phrases whose optional value is empty
  t = t.replace(new RegExp(` ?ή τηλεφωνικά στο ${EMPTY}`, 'g'), '');
  t = t.replace(new RegExp(` ?\\(${EMPTY}\\)`, 'g'), '');
  t = t.split('\n').filter((line) => !line.includes(EMPTY)).join('\n');

  // 4) Strip remaining operator HTML comments from the rendered output
  t = t.replace(/<!--[\s\S]*?-->/g, '');

  return t.trim();
}

/** Builder disclaimer (rendered LAST on the legal page, after the three documents).
 *  Variant: legalConfig.builderVariant if set, else deterministic from the business
 *  name — stable per site, different across the portfolio. */
export function renderBuilderDisclaimer(): string {
  const pick =
    legalConfig.builderVariant ??
    [...site.name].reduce((h, ch) => (h * 31 + ch.charCodeAt(0)) % 997, 7) % builderDisclaimers.length;
  const text = builderDisclaimers[pick].replace(/\[BUSINESS_NAME\]/g, site.name);
  return `### Αποποίηση Ευθύνης Κατασκευαστή Ιστότοπου\n${text}`;
}
